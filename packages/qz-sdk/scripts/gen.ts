// Regenerates everything in src/generated/ from the Foundry build and the Solidity constants.
//   forge build (in contracts/)  ->  node scripts/gen.ts   (npm run gen)
// Output is deterministic: running it twice, or on another machine with the same pinned solc, changes nothing.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { toEventSelector, toEventSignature } from 'viem';
import type { Abi, AbiEvent } from 'viem';

import { parseHookFlags, parseIntegerConstants } from './sol-eval.ts';
import { CONTRACTS, R1_CONTRACTS, R2_CONTRACTS } from '../src/contracts.ts';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, '..');
const repoRoot = resolve(pkgRoot, '..', '..');
const contractsDir = join(repoRoot, 'contracts');
const outDir = join(pkgRoot, 'src', 'generated');
const HEADER = '// GENERATED by scripts/gen.ts (npm run gen). Do not edit.\n';

const camel = (name: string) => name.charAt(0).toLowerCase() + name.slice(1);

function fail(message: string): never {
  console.error(`gen: ${message}`);
  process.exit(1);
}

// ───────────── guard: every interface file has an entry ─────────────
const interfaceFiles = readdirSync(join(contractsDir, 'src', 'interfaces'))
  .filter((f) => /^IQZ.+\.sol$/.test(f) && f !== 'IQZCommon.sol')
  .map((f) => f.replace(/^I/, '').replace(/\.sol$/, ''))
  .sort();
const expected = [...CONTRACTS].sort();
if (JSON.stringify(interfaceFiles) !== JSON.stringify(expected)) {
  fail(`contracts/src/interfaces and src/contracts.ts disagree:\n  files: ${interfaceFiles}\n  list : ${expected}`);
}

// ───────────── ABIs ─────────────
rmSync(outDir, { recursive: true, force: true });
mkdirSync(join(outDir, 'abis'), { recursive: true });

const abis: Record<string, Abi> = {};
for (const name of CONTRACTS) {
  const artifact = join(contractsDir, 'out', `I${name}.sol`, `I${name}.json`);
  if (!existsSync(artifact)) fail(`missing ${artifact}; run "forge build" in contracts/ first`);
  const abi = JSON.parse(readFileSync(artifact, 'utf8')).abi as Abi;
  abis[name] = abi;
  writeFileSync(
    join(outDir, 'abis', `${name}.ts`),
    `${HEADER}\nexport const ${camel(name)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
}

const abiIndex = [
  HEADER,
  ...CONTRACTS.map((n) => `import { ${camel(n)}Abi } from './${n}.ts';`),
  '',
  ...CONTRACTS.map((n) => `export { ${camel(n)}Abi };`),
  '',
  'export const abis = {',
  ...CONTRACTS.map((n) => `  ${n}: ${camel(n)}Abi,`),
  '} as const;',
  '',
].join('\n');
writeFileSync(join(outDir, 'abis', 'index.ts'), abiIndex);

// ───────────── event topics ─────────────
const topics: string[] = [];
for (const name of CONTRACTS) {
  const events = (abis[name] as Abi).filter((i): i is AbiEvent => i.type === 'event');
  events.sort((a, b) => a.name.localeCompare(b.name));
  for (const ev of events) {
    topics.push(
      `  '${name}.${ev.name}': { signature: '${toEventSignature(ev)}', topic0: '${toEventSelector(ev)}' },`,
    );
  }
}
writeFileSync(
  join(outDir, 'event-topics.ts'),
  `${HEADER}\nexport const eventTopics = {\n${topics.join('\n')}\n} as const;\n\nexport type EventKey = keyof typeof eventTopics;\n`,
);

// ───────────── constants ─────────────
const hooks = parseHookFlags(readFileSync(join(contractsDir, 'lib/v4-core/src/libraries/Hooks.sol'), 'utf8'));
const constants = parseIntegerConstants(
  readFileSync(join(contractsDir, 'src/lib/QZConstants.sol'), 'utf8'),
  (id) => {
    const v = hooks.get(id);
    if (v === undefined) throw new Error(`unknown identifier ${id}`);
    return v;
  },
);
writeFileSync(
  join(outDir, 'constants.ts'),
  `${HEADER}// Source: contracts/src/lib/QZConstants.sol (every value is a bigint; time values in seconds).\n\n${constants
    .map((c) => `export const ${c.name} = ${c.value}n; // ${c.type}`)
    .join('\n')}\n`,
);

// ───────────── addresses ─────────────
const addrSrc = readFileSync(join(contractsDir, 'src/lib/QZAddresses.sol'), 'utf8').replace(/\/\/[^\n]*/g, '');
const addressRows = [...addrSrc.matchAll(/address\s+internal\s+constant\s+(\w+)\s*=\s*(0x[0-9a-fA-F]{40})\s*;/g)].map(
  (m) => [m[1] as string, m[2] as string] as const,
);
writeFileSync(
  join(outDir, 'addresses.ts'),
  `${HEADER}// Source: contracts/src/lib/QZAddresses.sol (checksummed).\n\nexport const addresses = {\n${addressRows
    .map(([n, a]) => `  ${n}: '${a}',`)
    .join('\n')}\n} as const;\n`,
);

const { writeContractDoc } = await import('./gen-docs.ts'); // needs the files written above
const { fixtures } = await import('../src/fixtures.ts');
mkdirSync(join(pkgRoot, 'fixtures'), { recursive: true });
for (const [name, value] of Object.entries(fixtures)) {
  writeFileSync(join(pkgRoot, 'fixtures', `${name}.json`), `${JSON.stringify(value, null, 2)}\n`);
}
writeContractDoc(repoRoot);
console.log(
  `gen: ${CONTRACTS.length} ABIs, ${topics.length} event topics, ${constants.length} constants, ${addressRows.length} addresses, docs/CONTRACT.md tables`,
);
